// Framework-independent input engine. Nothing in this header depends on
// Fcitx, X11 or GLib: the front end translates native key events into `Key`.
#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <unordered_map>
#include <vector>

#include "config.h"
#include "dictionary.h"
#include "pinyin.h"

namespace zhiyi {

enum class KeyKind {
    kUnknown,
    kChar,           // ch holds the ASCII character
    kDigit,          // ch holds '0'..'9'
    kBackspace,
    kReturn,
    kEscape,
    kSpace,
    kPageUp,
    kPageDown,
    kToggleEnglish,  // tapped Shift, generated by the front end on key-up
};

struct Key {
    KeyKind kind = KeyKind::kUnknown;
    char ch = 0;
    bool ctrl = false;
    bool alt = false;
    bool shift = false;
};

struct Candidate {
    std::string text;
    std::string comment;
    std::size_t consumed = 0;   // pinyin bytes this candidate commits
    int kind = 0;               // 0 sentence, 1 exact, 2 initials, 3 prefix, 4 single
    std::int64_t score = 0;
};

struct EngineResult {
    bool consumed = false;
    std::string commit;         // text to send to the application
    bool display_changed = true;
};

class Engine {
public:
    // data_dir: read-only installation data (/usr/share/zhiyi/data)
    // user_dir: writable per-user data ($XDG_DATA_HOME/zhiyi)
    bool initialize(const std::string& data_dir, const std::string& user_dir);

    EngineResult process(const Key& key);
    // Select by an index inside the currently visible page (used by the
    // candidate callback and by the CLI tool).
    std::string select_visible(std::size_t index) { return select(index); }
    void reset();
    void save();

    bool ready() const { return dict_.is_open(); }
    std::string preedit() const { return raw_input_; }
    std::vector<Candidate> visible_candidates() const;
    std::size_t candidate_count() const { return candidates_.size(); }
    int page() const { return page_; }
    int page_count() const;
    bool english() const { return english_; }
    void set_english(bool value) { english_ = value; }
    const Config& config() const { return config_; }
    Config& mutable_config() { return config_; }
    void reload_config();

private:
    void refresh_candidates();
    void add_candidates(const std::vector<DictCandidate>& source, int kind,
                        std::size_t consumed, std::size_t limit);
    std::string compose_greedy(const std::string& input) const;
    std::string compose_syllables(const std::string& input) const;
    std::string english_punctuation(char ch);
    std::string commit_raw();
    void reset_composition();
    std::string select(std::size_t index);
    void load_user_dict();
    void load_config();

    Dictionary dict_;
    Dictionary initials_;
    PinyinTable pinyin_;
    ShuangpinTable shuangpin_;
    Config config_;
    std::string data_dir_;
    std::string user_dir_;
    std::string raw_input_;     // keys as typed (shown in the preedit)
    std::string input_;         // normalized pinyin used for lookups
    std::vector<Candidate> candidates_;
    int page_ = 0;
    bool english_ = false;
    bool quote_open_ = true;
    std::unordered_map<std::string, std::int32_t> user_freq_;
    static constexpr std::size_t kMaxInput = 64;
};

}  // namespace zhiyi
